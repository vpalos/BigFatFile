// Writes the simple case folding table used by name keys, for both the C# and the
// TypeScript implementation, from one pinned Unicode version.
// Run from the repository root: node sdk/unicode/generate-case-folding.mjs

import { writeFileSync } from "node:fs";

const version = "17.0.0";
const url = `https://www.unicode.org/Public/${version}/ucd/CaseFolding.txt`;

const text = await (await fetch(url)).text();
if (!text.startsWith(`# CaseFolding-${version}.txt`)) {
  throw new Error(`Unexpected content at ${url}`);
}

const pairs = [];
for (const line of text.split("\n")) {
  const match = /^([0-9A-F]+); ([CS]); ([0-9A-F]+);/.exec(line);
  if (match) {
    pairs.push([parseInt(match[1], 16), parseInt(match[3], 16)]);
  }
}
pairs.sort((a, b) => a[0] - b[0]);

const hex = (n) => "0x" + n.toString(16).toUpperCase().padStart(4, "0");
const rows = (values) => {
  const lines = [];
  for (let i = 0; i < values.length; i += 8) {
    lines.push("        " + values.slice(i, i + 8).map(hex).join(", ") + ",");
  }
  return lines.join("\n");
};
const header = `Generated by sdk/unicode/generate-case-folding.mjs from CaseFolding-${version}.txt, statuses C and S. Do not edit.`;

writeFileSync(
  "sdk/BigFatFile.Contracts/Names/CaseFolding.g.cs",
  `// ${header}

namespace BigFatFile.Contracts.Names;

internal static partial class CaseFolding
{
    public const string UnicodeVersion = "${version}";

    private static ReadOnlySpan<int> Sources =>
    [
${rows(pairs.map((p) => p[0]))}
    ];

    private static ReadOnlySpan<int> Targets =>
    [
${rows(pairs.map((p) => p[1]))}
    ];
}
`,
);

const tsRows = [];
for (let i = 0; i < pairs.length; i += 6) {
  tsRows.push(
    "  " +
      pairs
        .slice(i, i + 6)
        .map(([s, t]) => `[${hex(s)}, ${hex(t)}]`)
        .join(", ") +
      ",",
  );
}

writeFileSync(
  "sdk/@bigfatfile/client/src/contracts/caseFolding.g.ts",
  `// ${header}

export const unicodeVersion = "${version}";

export const caseFolding: ReadonlyMap<number, number> = new Map([
${tsRows.join("\n")}
]);
`,
);

console.log(`${pairs.length} mappings from Unicode ${version}`);
