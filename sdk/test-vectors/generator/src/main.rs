//! Writes chunking.json: the expected chunks of a set of inputs, computed with the
//! reference crates (fastcdc v2020 and blake3) and the parameters fixed in Contracts.

use fastcdc::v2020::{FastCDC, Normalization};
use serde::Serialize;
use serde_json::{Value, json};

const MIB: u64 = 1024 * 1024;
const MIN_SIZE: usize = 1024 * 1024;
const AVG_SIZE: usize = 4 * 1024 * 1024;
const MAX_SIZE: usize = 8 * 1024 * 1024;

#[derive(Serialize)]
struct ChunkOut {
    offset: u64,
    size: u64,
    hash: String,
}

/// One piece of a vector's input: BLAKE3 extended output of a seed, from an offset, or zeros.
enum Part {
    Xof { seed: &'static str, offset: u64, length: u64 },
    Zeros { length: u64 },
}

fn xof(seed: &'static str, length: u64) -> Part {
    Part::Xof { seed, offset: 0, length }
}

fn xof_from(seed: &'static str, offset: u64, length: u64) -> Part {
    Part::Xof { seed, offset, length }
}

fn materialise(parts: &[Part]) -> Vec<u8> {
    let mut data = Vec::new();
    for part in parts {
        match part {
            Part::Xof { seed, offset, length } => {
                let mut reader = blake3::Hasher::new().update(seed.as_bytes()).finalize_xof();
                reader.set_position(*offset);
                let start = data.len();
                data.resize(start + *length as usize, 0);
                reader.fill(&mut data[start..]);
            }
            Part::Zeros { length } => data.resize(data.len() + *length as usize, 0),
        }
    }
    data
}

fn describe(parts: &[Part]) -> Value {
    parts
        .iter()
        .map(|part| match part {
            Part::Xof { seed, offset, length } => {
                json!({ "kind": "xof", "seed": seed, "offset": offset, "length": length })
            }
            Part::Zeros { length } => json!({ "kind": "zeros", "length": length }),
        })
        .collect()
}

fn vector(name: &str, description: &str, parts: Vec<Part>) -> Value {
    let data = materialise(&parts);
    let chunks: Vec<ChunkOut> =
        FastCDC::with_level(&data, MIN_SIZE, AVG_SIZE, MAX_SIZE, Normalization::Level1)
            .map(|c| ChunkOut {
                offset: c.offset as u64,
                size: c.length as u64,
                hash: format!("blake3:{}", blake3::hash(&data[c.offset..c.offset + c.length]).to_hex()),
            })
            .collect();
    json!({
        "name": name,
        "description": description,
        "input": describe(&parts),
        "size": data.len(),
        "hash": format!("blake3:{}", blake3::hash(&data).to_hex()),
        "chunks": chunks,
    })
}

fn main() {
    let output = std::env::args().nth(1).expect("usage: bff-test-vectors <output.json>");

    let vectors = vec![
        vector("empty", "No bytes: no chunks.", vec![]),
        vector("one-byte", "A file smaller than the minimum chunk is one chunk.", vec![xof("one-byte", 1)]),
        vector("minimum", "Exactly the minimum chunk size: one chunk.", vec![xof("minimum", MIB)]),
        vector("minimum-plus-one", "One byte over the minimum.", vec![xof("minimum-plus-one", MIB + 1)]),
        vector("odd-length", "An odd length, so the last byte is never tested as a cut point.", vec![xof("odd-length", 5 * MIB + 3)]),
        vector("zeros", "No content to cut on: every chunk but the last is the maximum size.", vec![Part::Zeros { length: 20 * MIB }]),
        vector("random", "64 MiB of pseudo-random bytes.", vec![xof("random", 64 * MIB)]),
        vector(
            "random-with-insert",
            "The random input with 100 bytes inserted at 20 MiB. Only the chunks around the insert change.",
            vec![
                xof("random", 20 * MIB),
                xof("insert", 100),
                xof_from("random", 20 * MIB, 44 * MIB),
            ],
        ),
    ];

    let document = json!({
        "description": "Expected chunks for the content-defined chunker. Each input is a list of parts: \
                        'xof' is the BLAKE3 extended output of the UTF-8 seed, read from 'offset' for \
                        'length' bytes; 'zeros' is 'length' zero bytes. Generated by sdk/test-vectors/generator.",
        "chunker": {
            "algorithm": "fastcdc-2020",
            "minSize": MIN_SIZE,
            "averageSize": AVG_SIZE,
            "maxSize": MAX_SIZE,
            "normalizationLevel": 1,
        },
        "vectors": vectors,
    });

    let text = serde_json::to_string_pretty(&document).unwrap() + "\n";
    std::fs::write(&output, text).expect("cannot write the output file");
}
